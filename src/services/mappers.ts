import { EventItem, EventCategory, RuleBasedPlanMeta } from '../types/event';
import { BackendEventRow } from './api';

/**
 * Maps a frontend EventItem (or partial update) to the backend database schema.
 */
export function toBackend(event: Partial<EventItem>): {
  name?: string;
  event_type?: EventCategory;
  event_date?: string | null;
  location?: string | null;
  guest_count?: number | null;
  budget?: number | null;
  plan?: any;
} {
  const payload: any = {};

  if (event.title !== undefined) payload.name = event.title;
  if (event.category !== undefined) payload.event_type = event.category;
  if (event.date !== undefined) payload.event_date = event.date || null;
  if (event.location !== undefined) payload.location = event.location || null;
  if (event.targetGuests !== undefined) {
    payload.guest_count = Number.isFinite(event.targetGuests) ? Number(event.targetGuests) : null;
  }
  if (event.totalBudget !== undefined) {
    payload.budget = Number.isFinite(event.totalBudget) ? Number(event.totalBudget) : null;
  }

  // Construct workspace payload inside plan
  const workspace: any = {
    venueName: event.venueName ?? '',
    startTime: event.startTime ?? '10:00',
    endTime: event.endTime ?? '18:00',
    description: event.description ?? '',
    coverImage: event.coverImage ?? '',
    hostName: event.hostName ?? '',
    hostEmail: event.hostEmail ?? '',
    currency: event.currency ?? 'INR',
    timeline: event.timeline ?? [],
    budgetItems: event.budgetItems ?? [],
    guests: event.guests ?? [],
    tasks: event.tasks ?? [],
    vendors: event.vendors ?? [],
  };

  payload.plan = {
    workspace,
    ...(event.ruleBasedPlan ? { rule_based: event.ruleBasedPlan } : {}),
  };

  return payload;
}

/**
 * Defensive parser that transforms a backend row into the frontend EventItem.
 */
export function fromBackend(row: BackendEventRow): EventItem {
  const plan = row.plan && typeof row.plan === 'object' ? row.plan : {};
  const workspace = plan.workspace && typeof plan.workspace === 'object' ? plan.workspace : {};

  // Parse budget string or number safely
  let budgetNumber = 0;
  if (typeof row.budget === 'number') {
    budgetNumber = row.budget;
  } else if (typeof row.budget === 'string') {
    const cleaned = row.budget.replace(/[^0-9.-]+/g, '');
    const parsed = parseFloat(cleaned);
    budgetNumber = Number.isFinite(parsed) ? parsed : 0;
  }

  const category: EventCategory =
    row.event_type === 'wedding' || row.event_type === 'birthday' || row.event_type === 'community'
      ? row.event_type
      : 'wedding';

  // Rule-based metadata if generated by backend
  const ruleBasedPlan: RuleBasedPlanMeta = {
    warnings: Array.isArray(plan.warnings) ? plan.warnings : undefined,
    per_guest_cost: typeof plan.per_guest_cost === 'number' ? plan.per_guest_cost : undefined,
    days_until_event: typeof plan.days_until_event === 'number' ? plan.days_until_event : undefined,
    total_budget: typeof plan.total_budget === 'number' ? plan.total_budget : undefined,
    guest_count: typeof plan.guest_count === 'number' ? plan.guest_count : undefined,
    generated_by: typeof plan.generated_by === 'string' ? plan.generated_by : undefined,
  };

  return {
    id: String(row.id),
    title: row.name || 'Untitled Event',
    category,
    date: row.event_date || '',
    location: row.location || '',
    targetGuests: typeof row.guest_count === 'number' ? row.guest_count : 0,
    totalBudget: budgetNumber,
    createdAt: row.created_at || new Date().toISOString(),

    // Workspace fields with safe defaults
    venueName: typeof workspace.venueName === 'string' ? workspace.venueName : '',
    startTime: typeof workspace.startTime === 'string' ? workspace.startTime : '10:00',
    endTime: typeof workspace.endTime === 'string' ? workspace.endTime : '18:00',
    description: typeof workspace.description === 'string' ? workspace.description : '',
    coverImage: typeof workspace.coverImage === 'string' ? workspace.coverImage : '',
    hostName: typeof workspace.hostName === 'string' ? workspace.hostName : '',
    hostEmail: typeof workspace.hostEmail === 'string' ? workspace.hostEmail : '',
    currency: typeof workspace.currency === 'string' && workspace.currency ? workspace.currency : 'INR',
    timeline: Array.isArray(workspace.timeline) ? workspace.timeline : [],
    budgetItems: Array.isArray(workspace.budgetItems) ? workspace.budgetItems : [],
    guests: Array.isArray(workspace.guests) ? workspace.guests : [],
    tasks: Array.isArray(workspace.tasks) ? workspace.tasks : [],
    vendors: Array.isArray(workspace.vendors) ? workspace.vendors : [],
    ruleBasedPlan,
  };
}
